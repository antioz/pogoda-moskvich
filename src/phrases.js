// Генератор «настроенческого» прогноза в стиле уставшего москвича.
// На вход — нормализованная погода, на выход — одна короткая фраза.
//
// Принцип: WMO weather_code и температура определяют КАТЕГОРИЮ настроения,
// внутри категории фраза выбирается случайно — чтобы канал не повторялся изо дня в день.

/** Случайный элемент массива. */
function pick(list) {
  return list[Math.floor(Math.random() * list.length)];
}

/** "+30", "-5", "0" — температура со знаком, округлённая. */
function fmt(t) {
  const r = Math.round(t);
  if (r > 0) return `+${r}`;
  return `${r}`; // 0 и отрицательные уже с нужным знаком
}

// Категории осадков по WMO-коду (приоритет важнее температуры).
const THUNDER = new Set([95, 96, 99]);
const SNOW = new Set([71, 73, 75, 77, 85, 86]);
const FREEZING = new Set([56, 57, 66, 67]);
const RAIN = new Set([51, 53, 55, 61, 63, 65, 80, 81, 82]);
const FOG = new Set([45, 48]);

/**
 * @param {object} w
 * @param {number} w.tempMax   дневной максимум, °C
 * @param {number} w.tempMin   ночной минимум, °C
 * @param {number} w.code      WMO weather_code (дневной)
 * @param {number} w.cloud     облачность 0–100 %
 * @returns {string}
 */
function generateMessage({ tempMax, tempMin, code, cloud }) {
  const t = fmt(tempMax);

  // 1. Гроза — главный спецэффект, перебивает всё.
  if (THUNDER.has(code)) {
    return pick([
      `блиииин гроза щас как ёбнет ${t}`,
      `блиииин гроза, сидим дома ${t}`,
      `блииин громыхает, зонт не спасёт ${t}`,
      `блиииин гроза жесть, не выходи ${t}`,
    ]);
  }

  // 2. Снег.
  if (SNOW.has(code)) {
    return pick([
      `блиииин снег опять ${t}`,
      `блиииин завалило снегом ${t}`,
      `блиин снег, лопату доставай ${t}`,
      `блииин белым бело и ${t}`,
      `блиииин снежно и ${t}, зима не сдаётся`,
    ]);
  }

  // 3. Ледяной дождь — отдельный филиал ада.
  if (FREEZING.has(code)) {
    return pick([
      `блиииин гололёд, ноги береги ${t}`,
      `блиин ледяной дождь, каток на улице ${t}`,
      `блииин всё в наледи ${t}, аккуратно`,
    ]);
  }

  // 4. Дождь.
  if (RAIN.has(code)) {
    return pick([
      `блиииин опять дождь ${t}`,
      `блиин дождина, зонт не забудь ${t}`,
      `блииин мокро и ${t}, что за лето`,
      `блиииин льёт как из ведра ${t}`,
      `блиин сыро, дождь и ${t}`,
    ]);
  }

  // 5. Туман.
  if (FOG.has(code)) {
    return pick([
      `блииин туман, ничего не видно ${t}`,
      `блиин молоко за окном, туман и ${t}`,
      `блиииин туманище ${t}, как в кино`,
    ]);
  }

  // 6. Без осадков — настроение задаёт температура.
  const cloudy = cloud >= 60;

  if (tempMax >= 30) {
    return pick([
      `блиииииин жарко жесть ${t}`,
      `блиииин пекло ${t}, плавимся`,
      `блиииин ${t} это уже перебор`,
      `блиииин адская жара ${t}, прячемся в тень`,
    ]);
  }
  if (tempMax >= 25) {
    return pick([
      `блииин жарко ${t}`,
      `блиииин печёт ${t}, водички бы`,
      `блиин тепло аж ${t}, лето как лето`,
      `блиииин ${t} и солнце шпарит`,
    ]);
  }
  if (tempMax >= 18) {
    return cloudy
      ? pick([
          `блиин тепло но пасмурно ${t} и облачно`,
          `блииин ${t}, нормас но серенько`,
          `блиин ${t} и тучи, могло быть хуже`,
        ])
      : pick([
          `блиин кайф погодка ${t} и солнце`,
          `блииин тепло и ясно ${t}, гуляем`,
          `блиин ${t}, наконец-то по-человечески`,
        ]);
  }
  if (tempMax >= 10) {
    return cloudy
      ? pick([
          `блиииин пасмурно что за фигня ${t} и облачно`,
          `блиин серо и ${t}, осень в душе`,
          `блииин ${t} и тучи, куртку бери`,
        ])
      : pick([
          `блиин прохладно но ясно ${t}`,
          `блииин ${t}, свежо но солнечно`,
          `блиин ${t} и ветерок, бодрит`,
        ]);
  }
  if (tempMax >= 3) {
    return pick([
      `блиииин похоолодало ${t}`,
      `блиин зябко ${t}, утепляйся`,
      `блииин ${t}, шапку уже доставать?`,
      `блиин свежо аж ${t}, бррр`,
    ]);
  }
  if (tempMax >= -7) {
    return pick([
      `блиииин холодрыга ${t}`,
      `блиин морозит ${t}, кутаемся`,
      `блииин ${t}, нос отвалится`,
      `блиин зима пришла, ${t}`,
    ]);
  }
  // Жёсткий минус.
  return pick([
    `блиииин дубак ${t} жесть`,
    `блиин мороз ${t}, никуда не выходим`,
    `блииин ${t}, космический холод`,
    `блиин ${t} это уже издевательство`,
  ]);
}

export { generateMessage, fmt, pick };
